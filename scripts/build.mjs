import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const { name } = JSON.parse(read('package.json'));
const source = [read('src/mouse-gestures.js'), read('src/client.js')].join('\n');
const css = [read('src/browser.css'), read('src/gesture.css')].join('\n');
const folderIcon = `data:image/svg+xml;base64,${Buffer.from(read('src/folder.svg')).toString('base64')}`;
const sessionIcon = `data:image/svg+xml;base64,${Buffer.from(read('src/session.svg')).toString('base64')}`;

const menuFolderIcon = 'data:image/svg+xml;base64,' + Buffer.from(read('src/menu-folder.svg')).toString('base64');
const largeIconsMenuIcon = 'data:image/svg+xml;base64,' + Buffer.from(read('src/large-icons.svg')).toString('base64');
const listMenuIcon = 'data:image/svg+xml;base64,' + Buffer.from(read('src/list-view.svg')).toString('base64');

// DSH supplies React and its UI primitives through the client module loader.
const bundle = `// Generated by scripts/build.mjs.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory(require) {
    const id = ${JSON.stringify(name)};
    const react = require('react');
    const { createPortal, flushSync } = require('react-dom');
    const ui = require('@deepseek-ai/dsh-client-ui-primitives');
    const css = ${JSON.stringify(css)};
    const folderIcon = ${JSON.stringify(folderIcon)};
    const sessionIcon = ${JSON.stringify(sessionIcon)};
    const largeIconsMenuIcon = ${JSON.stringify(largeIconsMenuIcon)};
    const menuFolderIcon = ${JSON.stringify(menuFolderIcon)};
    const listMenuIcon = ${JSON.stringify(listMenuIcon)};
${source.trimEnd().split('\n').map(line => `    ${line}`).join('\n')}
    return { apply, inject };
  },
});
`;

mkdirSync(new URL('lib/', root), { recursive: true });
writeFileSync(new URL('lib/client.js', root), bundle);
